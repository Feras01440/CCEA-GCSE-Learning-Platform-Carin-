/**
 * Maths misconception vocabulary (our wording). `sources`, `firstSeen`, `lastSeen` are derived by
 * build-insights.mjs from the findings that cite each id. ledgerTag: method | accuracy | misread |
 * presentation | not-attempted | concept.
 */
const M = (id, label, statements, ledgerTag, note) => ({ id, label, statements, ledgerTag, ...(note ? { note } : {}) });

/** ExaminerSource shorthand, as in maths.insights-a.mjs. */
const C = (series, unit, q) => `ccea-cer:maths:${series}:${unit}:Q${q}`;

/**
 * MX: an entry whose report evidence is carried by `extraSources` instead of by an insight-card
 * finding. Used where an authored content bundle (packs/maths/content/<unit>/<topic>/bundle.json)
 * tags a distractor, a commonError or a find-the-mistake item with this misconception but no card
 * finding names it yet. The sources are the ones the bundle itself cites for those items: the
 * item's own `source` where the authors gave one, otherwise the examinerSources of the question(s)
 * carrying the tag. build-insights.mjs still derives `sources`, `firstSeen` and `lastSeen` from
 * them; validate-insights.mjs reports an uncited entry as a warning, not an error.
 */
const MX = (id, label, statements, ledgerTag, extraSources, note) => ({
  id,
  label,
  statements,
  ledgerTag,
  extraSources,
  ...(note ? { note } : {}),
});

